    index_arn: Str? = None
}

// Represents the input of a DeleteTable operation.
export struct DeleteTableInput {
    // The name of the table to delete. You can also provide the Amazon Resource
    // Name (ARN) of the table in this parameter.
    table_name: Str
}

// Represents the output of a DeleteTable operation.
export struct DeleteTableOutput {
    // Represents the properties of a table.
    table_description: TableDescription? = None
}

// A DynamoDB attribute value: one of the ten wire types. Recursive through
// `M` (a map of attributes) and `L` (a list of them). A number arrives as its
// decimal string, as DynamoDB sends it on the wire.
export namespace AttributeValue {
    // A string value (`S`).
    export struct S { value: Str }
    // A number, as its decimal string (`N`).
    export struct N { value: Str }
    // Binary data (`B`).
    export struct B { value: Bytes }
    // A string set (`SS`).
    export struct Ss { value: List<Str> }
    // A number set, each as its decimal string (`NS`).
    export struct Ns { value: List<Str> }
    // A binary set (`BS`).
    export struct Bs { value: List<Bytes> }
    // A map of attribute values (`M`).
    export struct M { value: Map<Str, AttributeValue> }
    // A list of attribute values (`L`).
    export struct L { value: List<AttributeValue> }
    // A boolean (`BOOL`).
    export struct Bool { value: Bool }
    // The null value (`NULL`); its `value` is always `true`.
    export struct Null { value: Bool }
}

export type AttributeValue = AttributeValue.S
    | AttributeValue.N
    | AttributeValue.B
    | AttributeValue.Ss
    | AttributeValue.Ns
    | AttributeValue.Bs
    | AttributeValue.M
    | AttributeValue.L
    | AttributeValue.Bool
    | AttributeValue.Null

// A code Ddb answers with: one arm per error the model names for these
// operations, and `Other` for anything else the service sends — throttling, an
// authorization failure, a code newer than this model. A legacy wire code is
// normalized to the model's name, so a code reads the same on every backend.
export type DdbErrorCode = "ConditionalCheckFailedException"
    | "InternalServerError"
    | "InvalidEndpointException"
    | "ItemCollectionSizeLimitExceededException"
    | "LimitExceededException"
    | "ProvisionedThroughputExceededException"
    | "ReplicatedWriteConflictException"
    | "RequestLimitExceeded"
    | "ResourceInUseException"
    | "ResourceNotFoundException"
    | "ThrottlingException"
    | "TransactionConflictException"
    | Other Str

// The service answered with an error: what it said, and the HTTP status it said
// it with.
export struct DdbError {
    code: DdbErrorCode,
    message: Str,
    // The HTTP status of the response.
    status: Int,
    // The service's id for the request, when it sent one: what AWS support asks for.
    request_id: Str? = None,
    // Set for `ConditionalCheckFailedException` only. Item which caused the
    // ConditionalCheckFailedException.
    item: Map<Str, AttributeValue>? = None,
    // Set for `ProvisionedThroughputExceededException` only. A list of
    // ThrottlingReason that provide detailed diagnostic information about why
    // the request was throttled.
    throttling_reasons: List<ThrottlingReason>? = None
}

// Everything an operation of [Ddb] can answer with instead of its output: the
// service's error, or an [AwsError] when there was no answer to read.
export type DdbFailure = DdbError | AwsError

// Amazon DynamoDB. Every member hands its [reply] to the provider and returns
// at once; the answer is the operation's output or a `Checked` [DdbFailure].
export effect Ddb {
    // The GetItem operation returns a set of attributes for the item with the
    // given primary key. If there is no matching item, GetItem does not return
    // any data and there will be no Item element in the response.
    fn get_item(input: GetItemInput, reply: Reply<Ok GetItemOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply

    // Creates a new item, or replaces an old item with a new item. If an item
    // that has the same primary key as the new item already exists in the
    // specified table, the new item completely replaces the existing item. You
    // can perform a conditional put operation (add a new item if one with the
    // specified primary key doesn't exist), or replace an existing item if it
    // has certain attribute values. You can return the item's attribute values
    // in the same operation, using the ReturnValues parameter.
    fn put_item(input: PutItemInput, reply: Reply<Ok PutItemOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply

    // Deletes a single item in a table by primary key. You can perform a
    // conditional delete operation that deletes the item if it exists, or if it
    // has an expected attribute value.
    fn delete_item(input: DeleteItemInput, reply: Reply<Ok DeleteItemOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply

    // You must provide the name of the partition key attribute and a single
    // value for that attribute. Query returns all items with that partition key
    // value. Optionally, you can provide a sort key attribute and use a
    // comparison operator to refine the search results.
    fn query(input: QueryInput, reply: Reply<Ok QueryOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply

    // The CreateTable operation adds a new table to your account. In an Amazon
    // Web Services account, table names must be unique within each Region. That
    // is, you can have two tables with same name if you create the tables in
    // different Regions.
    fn create_table(input: CreateTableInput, reply: Reply<Ok CreateTableOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply

    // The DeleteTable operation deletes a table and all of its items. After a
    // DeleteTable request, the specified table is in the DELETING state until
    // DynamoDB completes the deletion. If the table is in the ACTIVE state, you
    // can delete it. If a table is in CREATING or UPDATING states, then
    // DynamoDB returns a ResourceInUseException. If the specified table does
    // not exist, DynamoDB returns a ResourceNotFoundException. If table is
    // already in the DELETING state, no error is returned.
    fn delete_table(input: DeleteTableInput, reply: Reply<Ok DeleteTableOutput | Err Checked<DdbFailure>>) -> None
    => !input, !reply
}

// What a [FakeDdb] was asked, in order: one operation name per call.
export effect DdbCalls {
    // The names of the operations called so far (`get_item`, …).
    fn calls() -> List<Str>
}

// A recording double for [Ddb]: every call is noted by operation name — read
// them through [DdbCalls] — and answered with an empty output where the
// operation's output has no required members, otherwise with `AwsError { code:
// "NotStubbed" }`. A test that needs real answers implements [Ddb] itself.
export handler FakeDdb() of Ddb, DdbCalls {
    state {
        recorded: Mut List<Str> = Mut List()
    }

    fn get_item(input: GetItemInput, reply: Reply<Ok GetItemOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("get_item")
        reply.send(ok(GetItemOutput {}))
    }

    fn put_item(input: PutItemInput, reply: Reply<Ok PutItemOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("put_item")
        reply.send(ok(PutItemOutput {}))
    }

    fn delete_item(input: DeleteItemInput, reply: Reply<Ok DeleteItemOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("delete_item")
        reply.send(ok(DeleteItemOutput {}))
    }

    fn query(input: QueryInput, reply: Reply<Ok QueryOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("query")
        reply.send(err(checked<DdbFailure>(AwsError { code: "NotStubbed", message: "FakeDdb cannot answer query" })))
    }

    fn create_table(input: CreateTableInput, reply: Reply<Ok CreateTableOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("create_table")
        reply.send(ok(CreateTableOutput {}))
    }

    fn delete_table(input: DeleteTableInput, reply: Reply<Ok DeleteTableOutput | Err Checked<DdbFailure>>) -> None => !input, !reply {
        recorded.add("delete_table")
        reply.send(ok(DeleteTableOutput {}))
    }

    fn calls() -> List<Str> {
        return copy(recorded)
    }
}
