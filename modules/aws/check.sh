#!/usr/bin/env bash
# The aws module's own checks. The compiler's test suite does not know this
# module exists (user decision 2026-10-29: a dependency's tests live with
# it); run this after changing the module, its generator, or anything in the
# compiler its generated code or glue depends on.
#
#   modules/aws/check.sh            # everything
#   modules/aws/check.sh examples   # one part: examples | host | glue
#
# 1. examples: each example under examples/ is current (its checked-in
#    rust/ and kotlin/ trees are what `salvo compile` writes now) and runs to
#    its expected.txt on both backends — the parity claim.
# 2. host: the host project checked in under salvo/platform/ is what
#    `salvo platform generate` writes now, and it compiles against the SDKs:
#    `cargo check` on its Cargo.toml, Gradle's `compileKotlin` on its
#    build.gradle.kts (the setup an IDE opening the root gets).
# 3. glue: the generated host glue (salvo/platform/aws/**) compiles against
#    the real SDKs through the two live demos that reach it: `cargo check`,
#    and kotlinc over the tree with the classpath Gradle resolves the way a
#    build does (through the build.gradle.kts `salvo compile` writes).
#
# Parts 2 and 3 skip, saying so, when the SDKs are not available offline
# (the crates not in cargo's cache, Gradle unable to resolve); ONLINE=1 lets
# cargo and Gradle fetch them. They are what
# break when emission changes the names the glue is written against (`UnionN`,
# `Checked`, a module's Rust path, a Kotlin data class).
#
# SALVO names the compiler (default: the workspace's target/debug/salvo,
# built if missing). Scratch output goes to modules/aws/.check/ (ignored).
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
scratch="$here/.check"
gradlew="$here/codegen/gradlew"
if [ -z "${SALVO:-}" ]; then
    SALVO="$repo/target/debug/salvo"
    if [ ! -x "$SALVO" ]; then
        (cd "$repo" && cargo build -q -p salvo-cli) || exit 1
    fi
fi
only="${1:-all}"
offline="--offline"
[ "${ONLINE:-}" = 1 ] && offline=""
failures=0
fail() { echo "FAIL: $*" >&2; failures=$((failures + 1)); }
have() { command -v "$1" > /dev/null 2>&1; }

# The files a tree holds that salvo generated, relative to it, with content.
generated_digest() {
    (cd "$1" && grep -rlE '^(//|#) GENERATED by salvo' . 2>/dev/null | sort | while read -r f; do
        printf '%s ' "$f"; shasum < "$f"
    done)
}

check_examples() {
    for dir in "$here"/examples/*/; do
        name="$(basename "$dir")"
        for backend in rust kotlin; do
            out="$scratch/examples/$name/$backend"
            rm -rf "$out" && mkdir -p "$(dirname "$out")"
            if ! (cd "$dir" && "$SALVO" compile --backend "$backend" --target "$out" > "$out.log" 2>&1); then
                fail "examples/$name: salvo compile --backend $backend failed (see $out.log)"
                continue
            fi
            if ! diff -rq "$out" "$dir/$backend" > /dev/null; then
                fail "examples/$name/$backend is stale: run \`salvo compile\` in $dir"
            fi
            if ! have "$([ "$backend" = rust ] && echo rustc || echo kotlinc)"; then
                echo "skipping the $backend run of examples/$name: no toolchain on PATH"
                continue
            fi
            if ! (cd "$dir" && "$SALVO" run --backend "$backend" 2> "$out.run.log" | diff -u expected.txt - > "$out.diff"); then
                fail "examples/$name: the $backend run does not print expected.txt (see $out.diff, $out.run.log)"
            fi
        done
        echo "examples/$name: checked"
    done
}

check_host() {
    copy="$scratch/host"
    rm -rf "$copy" && mkdir -p "$copy"
    cp "$here/salvo.toml" "$copy/"
    rsync -a --exclude '.gradle' --exclude '.kotlin' --exclude 'target' --exclude 'Cargo.lock' "$here/salvo" "$copy/"
    if ! (cd "$copy" && "$SALVO" platform generate --backend '*' > "$scratch/host.log" 2>&1); then
        fail "host: salvo platform generate failed (see $scratch/host.log)"
        return
    fi
    if [ "$(generated_digest "$here/salvo/platform")" != "$(generated_digest "$copy/salvo/platform")" ]; then
        fail "host: salvo/platform is stale: run \`salvo platform generate --backend '*'\` in $here"
    fi
    if have cargo; then
        if out="$(CARGO_TARGET_DIR="$scratch/cargo" cargo check $offline --quiet --manifest-path "$copy/salvo/platform/Cargo.toml" 2>&1)"; then
            echo "host: the Rust host crate compiles"
        elif grep -qE 'offline|no matching package' <<< "$out"; then
            echo "skipping the Rust host crate: the SDK crates are not in cargo's cache"
        else
            fail "host: the Rust host crate does not compile:"$'\n'"$out"
        fi
    fi
    if have java; then
        if out="$("$gradlew" $offline --quiet --project-dir "$copy/salvo/platform" compileKotlin 2>&1)"; then
            echo "host: the Gradle project compiles"
        elif grep -qE 'was not found in any of the following sources|Could not resolve' <<< "$out"; then
            echo "skipping the Gradle project: the Kotlin plugin or the SDK is not cached"
        else
            fail "host: the Gradle project does not compile:"$'\n'"$out"
        fi
    fi
}

check_glue() {
    for demo in sqs_live s3_live; do
        src="$here/demo/$demo"
        if have cargo && have rustc; then
            out="$scratch/glue/rs_$demo"
            rm -rf "$out"
            if ! (cd "$src" && "$SALVO" compile --backend rust --target "$out" > "$out.log" 2>&1); then
                fail "glue $demo: salvo compile --backend rust failed (see $out.log)"
            elif res="$(CARGO_TARGET_DIR="$scratch/cargo" cargo check $offline --quiet --manifest-path "$out/Cargo.toml" 2>&1)"; then
                echo "glue $demo: the Rust glue compiles"
            elif grep -qE 'offline|no matching package' <<< "$res"; then
                echo "skipping the Rust glue of $demo: the SDK crates are not in cargo's cache"
            else
                fail "glue $demo: the Rust glue does not compile:"$'\n'"$res"
            fi
        fi
        if have kotlinc && have java; then
            out="$scratch/glue/kt_$demo"
            rm -rf "$out"
            if ! (cd "$src" && "$SALVO" compile --backend kotlin --target "$out" > "$out.log" 2>&1); then
                fail "glue $demo: salvo compile --backend kotlin failed (see $out.log)"
                continue
            fi
            if ! res="$("$gradlew" --quiet --project-dir "$out" salvoClasspath 2>&1)"; then
                echo "skipping the Kotlin glue of $demo: Gradle could not resolve the SDK:"$'\n'"$res"
                continue
            fi
            classpath="$(paste -sd: "$out/.salvo_gradle/classpath.txt")"
            # shellcheck disable=SC2046
            if res="$(kotlinc $(find "$out" -name '*.kt' -not -path '*/.salvo_gradle/*') -nowarn -cp "$classpath" -d "$out/.classes" 2>&1)"; then
                echo "glue $demo: the Kotlin glue compiles"
            else
                fail "glue $demo: the Kotlin glue does not compile:"$'\n'"$res"
            fi
        fi
    done
}

mkdir -p "$scratch/glue"
case "$only" in
    all) check_examples; check_host; check_glue ;;
    examples) check_examples ;;
    host) check_host ;;
    glue) check_glue ;;
    *) echo "usage: $0 [examples|host|glue]" >&2; exit 2 ;;
esac
if [ "$failures" -gt 0 ]; then
    echo "$failures check(s) failed" >&2
    exit 1
fi
echo "all checks passed"
