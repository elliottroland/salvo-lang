//! [test-run] The generated harness: a Salvo program that runs the tests.
//!
//! `salvo test` synthesizes **one Salvo module** and compiles it with the rest
//! of the sources, exactly as `salvo run` would (user decision 2026-09-23,
//! TF-4 option A). Nothing about running tests is backend-specific as a
//! result: the two backends already agree about the language, so they agree
//! about the harness, and neither emitter needed a line of test-shaped code.
//!
//! The harness prints a **protocol**, not the report:
//!
//! ```text
//! ##salvo-test begin heap :: one element comes back out
//! ##salvo-test ok
//! ##salvo-test fail expected 9, got 5
//! ```
//!
//! and the runner renders what the user reads [test-report]. Two reasons,
//! both decided rather than incidental: the report is coloured, and Salvo
//! string literals have no escape for the ESC byte — a language question, not
//! a testing one; and the per-test milliseconds come from timing the protocol
//! lines as they stream, so a test needs no clock capability and the report's
//! shape stays identical on both backends by construction.

use salvo_core::TestCase;

/// The module the harness is synthesized into. Underscore-leading, so no
/// user module path can collide with it ([name-casing] reserves nothing here,
/// but a Salvo file is never named this).
pub const HARNESS_MODULE: &str = "__salvo_test_main";

/// The line the harness prints before running a test, followed by its id.
pub const BEGIN: &str = "##salvo-test begin ";
/// The line the harness prints after a test that completed.
pub const OK: &str = "##salvo-test ok";
/// The line the harness prints after a test that threw, followed by the
/// failure's text.
pub const FAIL: &str = "##salvo-test fail ";
/// [test-property] A line of a failure's detail, printed before its verdict
/// and shown under it: where a property was falsified, its parameters, how
/// to run it again.
pub const DETAIL: &str = "##salvo-test detail ";
/// [test-property] The verdict of a property whose simplest failure passed
/// when replayed, followed by the failure's text. Counted as a failure.
pub const FLAKY: &str = "##salvo-test flaky ";

/// [test-kind] What the harness hands every test's run: the `--arg`
/// flags, the manifest's `[test.args]`, and the seed of this run.
#[derive(Clone, Debug, Default)]
pub struct HarnessConfig {
    pub flags: Vec<(String, String)>,
    pub manifest: Vec<(String, String)>,
    pub run_seed: i64,
}

/// A `List<Str>` literal of `items`.
fn str_list(items: &[&String]) -> String {
    if items.is_empty() {
        return "List<Str>()".to_string();
    }
    let parts: Vec<String> = items.iter().map(|s| format!("\"{}\"", escape(s))).collect();
    format!("List({})", parts.join(", "))
}

/// [test-run] The harness module's source, for `tests` in report order.
///
/// One `try` per test [test-fail]: a test that completes is `Ok`, a test whose
/// assertion threw is `Thrown Failure`, and `when` reads the two arms like any
/// other union — which is the whole of why the failure channel needed no new
/// language surface.
pub fn harness_source(tests: &[TestCase], config: &HarnessConfig) -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by `salvo test` — the test harness [test-run].\n\
         //\n\
         // Not written to disk anywhere the compiler reads sources from: it is\n\
         // synthesized into the source set, compiled with the program, and\n\
         // prints the protocol the runner renders as the report.\n\
         //\n\
         // No `import std.test`: the harness is a test file, so `std.test` is\n\
         // implicitly available [test-implicit-import] — and an explicit import\n\
         // of it beside an `import <module>.test` was ambiguous.\n",
    );
    // One import per annex module: the synthesized test fns are exported from
    // the annex they were written in [test-run].
    // `std.core`'s annexes are visible without one, like `std.core` itself.
    let mut annexes: Vec<String> = tests
        .iter()
        .filter(|t| !t.tested.is_std_core())
        .map(|t| format!("{}.test", t.tested))
        .collect();
    annexes.sort();
    annexes.dedup();
    for annex in &annexes {
        out.push_str(&format!("import {annex}\n"));
    }
    // [test-kind] The harness holds one runtime's tests, never both: the
    // runner writes one program per runtime. A virtual test may spawn.
    let virtual_runtime = tests.iter().any(|t| t.runtime == "virtual");
    out.push_str(if virtual_runtime {
        "\nfn main() [use, spawn] {\n    use StdConsole()\n"
    } else {
        "\nfn main() [use] {\n    use StdConsole()\n"
    });
    let flag_keys: Vec<&String> = config.flags.iter().map(|(k, _)| k).collect();
    let flag_values: Vec<&String> = config.flags.iter().map(|(_, v)| v).collect();
    let manifest_keys: Vec<&String> = config.manifest.iter().map(|(k, _)| k).collect();
    let manifest_values: Vec<&String> = config.manifest.iter().map(|(_, v)| v).collect();
    out.push_str(&format!(
        "    let config = TestConfig {{ flag_keys: {}, flag_values: {}, manifest_keys: {}, manifest_values: {}, seed: {}L }}\n",
        str_list(&flag_keys),
        str_list(&flag_values),
        str_list(&manifest_keys),
        str_list(&manifest_values),
        config.run_seed,
    ));
    // [test-kind] One uniform arm: the test's run answers its verdict, which
    // a std fn prints as the protocol. What the kind does around the body
    // (catching a trap, entering a runtime, shrinking) is the kind's.
    for test in tests {
        out.push_str(&format!(
            "\n    println(\"{BEGIN}{}\")\n    print_verdict({}(config))\n",
            escape(&test.id()),
            test.fn_name,
        ));
    }
    out.push_str("}\n");
    out
}

/// A test name reaching a Salvo string literal. Names come from source, so
/// they can hold quotes, backslashes and `$`.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use salvo_core::ModulePath;

    fn case(name: &str, fn_name: &str, runtime: &str) -> TestCase {
        TestCase {
            file: 0,
            tested: ModulePath(vec!["heap".to_string()]),
            name: name.to_string(),
            fn_name: fn_name.to_string(),
            runtime: runtime.to_string(),
        }
    }

    /// [test-kind] One arm per test: begin, then the verdict its run answers.
    #[test]
    fn synthesizes_one_arm_per_test() {
        let src = harness_source(&[case("pops in order", "__salvo_test_heap_test_0", "threaded")], &HarnessConfig::default());
        assert!(src.contains("import heap.test\n"), "{src}");
        assert!(src.contains("print_verdict(__salvo_test_heap_test_0(config))"), "{src}");
        assert!(src.contains("println(\"##salvo-test begin heap :: pops in order\")"), "{src}");
        assert!(src.contains("fn main() [use] {"), "{src}");
        assert_eq!(src.matches("import heap.test").count(), 1);
    }

    /// [test-kind] A virtual-runtime program may spawn, and the config carries
    /// the flags, the manifest's arguments and the run's seed.
    #[test]
    fn a_virtual_program_may_spawn_and_carries_the_config() {
        let config = HarnessConfig {
            flags: vec![("runs".to_string(), "500".to_string())],
            manifest: vec![("seed".to_string(), "7".to_string())],
            run_seed: 99,
        };
        let src = harness_source(&[case("ticks", "__salvo_test_heap_test_0", "virtual")], &config);
        assert!(src.contains("fn main() [use, spawn] {"), "{src}");
        assert!(src.contains("flag_keys: List(\"runs\"), flag_values: List(\"500\")"), "{src}");
        assert!(src.contains("manifest_keys: List(\"seed\"), manifest_values: List(\"7\"), seed: 99L"), "{src}");
        assert!(!src.contains("trapped_by"), "{src}");
    }

    /// A name is source text, so it is escaped into the literal.
    #[test]
    fn escapes_names() {
        let src = harness_source(&[case("a \"quoted\" ${name}", "__salvo_test_heap_test_0", "threaded")], &HarnessConfig::default());
        assert!(
            src.contains("begin heap :: a \\\"quoted\\\" \\${name}"),
            "{src}"
        );
    }

    /// The protocol lines `std.test`'s `print_verdict` prints are the ones the
    /// runner reads: the two ends spell them separately.
    #[test]
    fn std_prints_the_protocol_the_runner_reads() {
        let std_test = include_str!("../../../lib/std/test.sv");
        for line in [OK, FAIL.trim_end(), DETAIL.trim_end(), FLAKY.trim_end()] {
            assert!(std_test.contains(&format!("\"{line}")), "std.test does not print `{line}`");
        }
    }
}
