//! [protocol-lock] `salvo.lock`: the protocol hash of every actor effect a
//! project declares, recorded against the project's `version`, so a protocol
//! change that ships without a version bump fails the build (user decision
//! 2026-09-26, the network round's N-9; shape decided 2026-09-29 with the
//! manifest).
//!
//! ```toml
//! version = "0.1.0"
//!
//! [protocols]
//! Counter = "3f2a9c1e0b7d5a44"
//! Timer = "9c0e11aa5f3b2d10"
//! ```
//!
//! Written by every build when the file is absent or when `[project] version`
//! changed; compared otherwise. A mismatch at the same version is an error
//! naming the effect and both hashes, and the remedy is bumping the version —
//! there is no `--relock`, since the whole point is that a silent protocol
//! change cannot ship. Only the project's own actor effects are locked, never
//! std's; a protocol without a wire form has no hash and is not listed.

use std::collections::BTreeMap;
use std::path::Path;

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Lock {
    pub version: Option<String>,
    #[serde(default)]
    pub protocols: BTreeMap<String, String>,
}

impl Lock {
    pub fn read(path: &Path) -> Result<Option<Lock>, String> {
        if !path.is_file() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("failed to read `{}`: {e}", path.display()))?;
        toml::from_str(&text)
            .map(Some)
            .map_err(|e| format!("`{}`: {} [protocol-lock]", path.display(), e.message()))
    }

    pub fn write(&self, path: &Path) -> Result<(), String> {
        let text = toml::to_string(self).map_err(|e| e.to_string())?;
        let text = format!(
            "# Generated by `salvo` [protocol-lock]: the protocol hash of every actor\n\
             # effect this project declares, at this version. A hash that changes\n\
             # without a version bump fails the build; bump `version` in salvo.toml.\n{text}"
        );
        std::fs::write(path, text).map_err(|e| format!("failed to write `{}`: {e}", path.display()))
    }
}

/// What reconciling the lock against the current build decided.
#[derive(Debug, PartialEq)]
pub enum LockOutcome {
    /// Nothing to lock (no actor protocols) and no file: nothing written.
    Nothing,
    /// The file was written (absent, or the version changed).
    Written,
    /// The file agrees.
    Unchanged,
}

/// [protocol-lock] Reconciles `current` (effect → hash, the project's own actor
/// protocols) with the lock at `path` for the manifest's `version`.
///
/// `Err` is the mismatch, rendered: which effect, both hashes, the remedy.
pub fn reconcile(
    path: &Path,
    version: Option<&str>,
    current: &BTreeMap<String, String>,
) -> Result<LockOutcome, String> {
    let existing = Lock::read(path)?;
    let fresh = Lock {
        version: version.map(str::to_string),
        protocols: current.clone(),
    };
    let Some(existing) = existing else {
        if current.is_empty() {
            return Ok(LockOutcome::Nothing);
        }
        fresh.write(path)?;
        return Ok(LockOutcome::Written);
    };
    if existing.version != fresh.version {
        // A new version may change any protocol: re-lock.
        fresh.write(path)?;
        return Ok(LockOutcome::Written);
    }
    let mut changed: Vec<String> = Vec::new();
    for (effect, hash) in current {
        if let Some(locked) = existing.protocols.get(effect) {
            if locked != hash {
                changed.push(format!(
                    "`{effect}` was `{locked}` and is now `{hash}`"
                ));
            }
        }
    }
    if !changed.is_empty() {
        return Err(format!(
            "protocol changed without a version bump: {} — at version {}, `{}` locks the \
             protocols a deployed peer was built against, so a rolling fleet would meet \
             two shapes under one name. Bump `[project] version` in salvo.toml, and the \
             lock is rewritten [protocol-lock]",
            changed.join("; "),
            fresh.version.as_deref().unwrap_or("(none)"),
            path.display()
        ));
    }
    if existing.protocols != fresh.protocols {
        // Only additions or removals: a new protocol, or one deleted. Neither
        // breaks a peer on the protocols it shares, so the lock follows.
        fresh.write(path)?;
        return Ok(LockOutcome::Written);
    }
    Ok(LockOutcome::Unchanged)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join("salvo_lock_tests");
        std::fs::create_dir_all(&dir).unwrap();
        let p = dir.join(name);
        let _ = std::fs::remove_file(&p);
        p
    }

    #[test]
    fn a_changed_hash_at_the_same_version_is_refused_and_a_bump_relocks() {
        let path = tmp("a.lock");
        let mut current = BTreeMap::new();
        current.insert("Counter".to_string(), "aaaa".to_string());
        assert_eq!(reconcile(&path, Some("1"), &current).unwrap(), LockOutcome::Written);
        assert_eq!(reconcile(&path, Some("1"), &current).unwrap(), LockOutcome::Unchanged);
        current.insert("Counter".to_string(), "bbbb".to_string());
        let err = reconcile(&path, Some("1"), &current).unwrap_err();
        assert!(err.contains("`Counter` was `aaaa` and is now `bbbb`"), "{err}");
        assert_eq!(reconcile(&path, Some("2"), &current).unwrap(), LockOutcome::Written);
        // A new protocol is an addition, not a break.
        current.insert("Timer".to_string(), "cccc".to_string());
        assert_eq!(reconcile(&path, Some("2"), &current).unwrap(), LockOutcome::Written);
    }

    #[test]
    fn no_protocols_and_no_file_writes_nothing() {
        let path = tmp("b.lock");
        assert_eq!(reconcile(&path, None, &BTreeMap::new()).unwrap(), LockOutcome::Nothing);
        assert!(!path.exists());
    }
}
