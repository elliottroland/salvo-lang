//! [kt-runtime-source] The backend's *runtime modules* — `runtime/*.kt`,
//! included verbatim by the emitter and written into a program's output when
//! it touches the feature — compiled directly by `kotlinc`.
//!
//! Same reasoning as the Rust backend's `runtime_tests.rs`: these were Rust
//! string literals inside `emit.rs`, so they were only ever compiled as part
//! of a whole generated program and only ever reviewed as escaped text. As
//! real source files they are verified on their own here.
//!
//! Skipped when `kotlinc` is not on PATH.

use std::process::Command;

/// Every static runtime module. A new one belongs here as soon as it exists.
/// (`bytes.kt` was added by the filesystem work without joining this list;
/// it is here now, which is what makes this test complete rather than a
/// sample.)
const RUNTIME_MODULES: &[&str] =
    &["throw.kt", "compare.kt", "bytes.kt", "scheduler.kt", "hosttime.kt"];

/// The bytes the emitter will splice, read from the same path `include_str!`
/// reads at compile time.
fn runtime_source(file: &str) -> String {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("runtime")
        .join(file);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("failed to read the runtime module {}: {e}", path.display()))
}

/// Compiles one runtime module on its own and asserts that `kotlinc`
/// accepted it. Warnings are asserted away for the same reason as on Rust:
/// this code lands in user output, where the user cannot fix it.
fn compile_runtime_module(file: &str) {
    let kotlinc = salvo_testkit::kotlinc(env!("CARGO_TARGET_TMPDIR"));
    if !kotlinc.available {
        return;
    }
    let source = runtime_source(file);
    let parts: Vec<&[u8]> = vec![
        b"kotlin-runtime-module",
        kotlinc.version.as_bytes(),
        file.as_bytes(),
        source.as_bytes(),
    ];
    let Some(stamp) = salvo_testkit::cached(
        env!("CARGO_TARGET_TMPDIR"),
        &format!("kotlin-runtime {file}"),
        &parts,
    ) else {
        return;
    };
    let dir = salvo_testkit::scratch(env!("CARGO_TARGET_TMPDIR"), &format!("rt-{file}"));
    let src = dir.join(file);
    std::fs::write(&src, &source).expect("failed to write the runtime module");
    // [time-timer] `scheduler.kt`'s deadline thread reads the monotonic clock,
    // so `hosttime.kt` is compiled beside it exactly as the emitter emits the
    // two together. Every other module stands alone, and `hosttime.kt` is
    // checked on its own through this same list.
    let mut sources = vec![src.clone()];
    if file == "scheduler.kt" {
        let hosttime = dir.join("hosttime.kt");
        std::fs::write(&hosttime, runtime_source("hosttime.kt"))
            .expect("failed to write the time runtime");
        sources.push(hosttime);
    }
    let out = Command::new("kotlinc")
        .args(&sources)
        .arg("-d")
        .arg(dir.join("classes"))
        .output()
        .expect("failed to run kotlinc");
    let noise = String::from_utf8_lossy(&out.stderr);
    assert!(
        out.status.success(),
        "kotlinc rejected runtime/{file}:\n{noise}"
    );
    assert!(
        !noise.contains("warning:"),
        "runtime/{file} compiles with warnings, which would land in user output:\n{noise}"
    );
    stamp.verified();
}

#[test]
fn every_runtime_module_compiles_warning_free() {
    for file in RUNTIME_MODULES {
        compile_runtime_module(file);
    }
}

/// A runtime module is spliced into user output, so it carries the
/// generated-by header and a trailing newline like everything else the
/// emitter writes.
#[test]
fn runtime_modules_carry_the_generated_header() {
    for file in RUNTIME_MODULES {
        let source = runtime_source(file);
        assert!(
            source.starts_with("// Generated by the Salvo compiler:"),
            "runtime/{file} must open with the generated-by header"
        );
        assert!(
            source.ends_with('\n'),
            "runtime/{file} must end with a newline"
        );
    }
}

// ===== The scheduler's *behaviour* — asynchronous effect handlers' runtime
// ([actor-kind] … [actor-watch]) =====
//
// **The scenarios and the expected output are verbatim the Rust backend's
// `runtime_tests.rs`** — that equality is the parity assertion: the two
// schedulers implement one decided design (run-to-completion activations,
// per-actor bounded queues that block the sender, replies with reserved
// capacity, the gate, death by faulted activation with `watch`, sends to
// the dead as no-ops, the idle-with-parked-gates report), so they must
// answer identically.
//
// All the drivers are compiled in **one** `kotlinc` invocation and then run
// in sequence: a `kotlinc` start-up costs about as much as a small compile
// (COMPLETED.md's gotchas), so one invocation per case would dominate the
// suite. Each driver gets its own package, since every one of them declares
// `MainKt`.

/// One behaviour case: a driver program, its expected stdout, whether the
/// program is expected to succeed, and a stderr marker to look for.
struct SchedulerCase {
    tag: &'static str,
    driver: &'static str,
    expected_stdout: &'static str,
    expect_success: bool,
    stderr_contains: &'static str,
}

/// Runs a child process with a wall-clock limit, so a scheduler bug shows
/// up as a failing test rather than a hung suite (AGENTS.md: watch the
/// clock).
fn wait_with_timeout(mut child: std::process::Child, secs: u64) -> std::process::Output {
    let start = std::time::Instant::now();
    loop {
        if let Some(_status) = child.try_wait().expect("failed to poll the child") {
            return child
                .wait_with_output()
                .expect("failed to collect the child's output");
        }
        if start.elapsed() > std::time::Duration::from_secs(secs) {
            let _ = child.kill();
            let out = child
                .wait_with_output()
                .expect("failed to collect the child's output");
            panic!(
                "the scheduler program did not finish within {secs}s (deadlock or lost wakeup)\
                 \nstdout so far:\n{}\nstderr so far:\n{}",
                String::from_utf8_lossy(&out.stdout),
                String::from_utf8_lossy(&out.stderr)
            );
        }
        std::thread::sleep(std::time::Duration::from_millis(20));
    }
}

