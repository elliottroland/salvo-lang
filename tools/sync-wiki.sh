#!/usr/bin/env bash
# Copies docs/language/ into the GitHub wiki checkout at wiki/.
#
# The wiki is a *separate* git repository (gitignored by this one) whose only
# job is to make the language docs readable on GitHub. It is **generated**:
# edit docs/language/, run this, and commit inside wiki/. Editing a wiki page
# directly is lost work.
#
#   tools/sync-wiki.sh          write the pages
#   tools/sync-wiki.sh --check  exit non-zero if the wiki is out of date
#
# GitHub wikis are flat and name a page by its file, so `Data-and-Types.md`
# becomes the page "Data and Types". `_Sidebar.md` gives every page the same
# navigation, and `Home.md` keeps its hand-written introduction with a
# generated contents table appended.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/docs/language"
wiki="$root/wiki"
check=0
[ "${1:-}" = "--check" ] && check=1

if [ ! -d "$wiki" ]; then
  echo "sync-wiki: no wiki/ checkout — clone the wiki repository there first:" >&2
  echo "  git clone https://github.com/elliottroland/salvo-lang.wiki.git wiki" >&2
  exit 1
fi

# The reading order is the index's: page links in docs/language/README.md, in
# the order they appear. Keeping one order in one place is what stops the
# sidebar and the index from drifting apart.
pages=()
while IFS= read -r page; do
  pages+=("$page")
done < <(grep -o '](\([A-Za-z-]*\)\.md)' "$src/README.md" | sed 's/](\(.*\)\.md)/\1/')

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# One page per file, with the "generated" banner the first thing a reader (or
# an editor) sees.
for page in "${pages[@]}"; do
  title="${page//-/ }"
  {
    printf '<!-- Generated from docs/language/%s.md by tools/sync-wiki.sh. Edit that file, not this page. -->\n\n' "$page"
    cat "$src/$page.md"
  } > "$tmp/$page.md"
done

# The sidebar: the same order, as wiki links.
{
  printf '### The Salvo language\n\n'
  printf '* [[Home]]\n'
  for page in "${pages[@]}"; do
    printf '* [[%s]]\n' "${page//-/ }"
  done
} > "$tmp/_Sidebar.md"

# Home keeps whatever prose it has above the marker, and the contents table
# below it is ours.
marker='<!-- contents: generated by tools/sync-wiki.sh -->'
{
  if [ -f "$wiki/Home.md" ]; then
    # Everything above the marker is the page's own prose; awk rather than
    # sed because the marker is an HTML comment full of slashes.
    awk -v m="$marker" 'index($0, m) { exit } { print }' "$wiki/Home.md"
  fi
  printf '%s\n\n## Contents\n\n' "$marker"
  for page in "${pages[@]}"; do
    printf '* [[%s]]\n' "${page//-/ }"
  done
} > "$tmp/Home.md"

if [ "$check" = 1 ]; then
  stale=0
  for f in "$tmp"/*.md; do
    name="$(basename "$f")"
    if [ ! -f "$wiki/$name" ] || ! diff -q "$f" "$wiki/$name" >/dev/null; then
      echo "sync-wiki: out of date: $name" >&2
      stale=1
    fi
  done
  # A page the wiki carries but the index no longer lists is stale too.
  for f in "$wiki"/*.md; do
    name="$(basename "$f")"
    [ -f "$tmp/$name" ] || { echo "sync-wiki: orphaned page: $name" >&2; stale=1; }
  done
  [ "$stale" = 0 ] || { echo "sync-wiki: run tools/sync-wiki.sh" >&2; exit 1; }
  echo "sync-wiki: up to date (${#pages[@]} pages)"
  exit 0
fi

# Remove pages the index dropped, then write.
for f in "$wiki"/*.md; do
  name="$(basename "$f")"
  [ -f "$tmp/$name" ] || rm -f "$f"
done
cp "$tmp"/*.md "$wiki/"
echo "sync-wiki: wrote ${#pages[@]} pages + Home.md and _Sidebar.md into wiki/"
